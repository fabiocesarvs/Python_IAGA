a = int(input("Digite o primeiro número: "))
b = int(input("Digite o segundo número: "))

soma = a + b
sub = a - b
mult = a * b
divInt = a // b
divReal = a / b
resto = a % b

print()
print(f"A soma entre {a} e {b} é: {soma}")
print(f"A subtração entre {a} e {b} é: {sub}")
print(f"A multiplicação entre {a} e {b} é: {mult}")
print(f"A divisão inteira entre {a} e {b} é: {divInt}")
print(f"A divisão real entre {a} e {b} é: {divReal}")
print(f"O resto da divisão entre {a} e {b} é: {resto}")